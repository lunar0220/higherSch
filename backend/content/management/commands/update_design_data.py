# Команда подгоняет тестовые данные под макет: python manage.py update_design_data
#  - пункты тарифов получают переносы строк, как на макете (знак "|" = перенос);
#  - факты о преподавателе Валерии Владимировне приводятся к тексту макета.
# Остальные данные не трогает.
from django.core.management.base import BaseCommand

from content.models import Teacher
from courses.models import Tariff

FEATURES = {
    "Стандарт": (
        "Диагностика|и персональный план\n"
        "Занятия по 1 предмету:|видеоуроки и вебинар\n"
        "Задания с автопроверкой\n"
        "Один пробный экзамен|в месяц\n"
        "Чат учеников"
    ),
    "Про": (
        "Всё из «Стандарта»\n"
        "Куратор проверяет|домашние задания\n"
        "Разбор ошибок после|каждого пробника\n"
        "2 пробных экзамена|в месяц\n"
        "Ежемесячный отчёт"
    ),
    "Про+": (
        "Всё из «Про»\n"
        "Две индивидуальные|консультации с препо-|давателем в месяц\n"
        "Личный наставник и|корректировка плана\n"
        "Помощь с выбором вуза|и стратегией поступления\n"
        "Ежемесячный созвон"
    ),
}

VALERIA_FACTS = (
    "Преподаватель английского языка с 8-летним стажем\n"
    "28 стобалльников и 2 472 сдали на 80+\n"
    "3 красных диплома о высшем образовании\n"
    "Ездила в США на 3,5 месяца по студенческой программе"
)


class Command(BaseCommand):
    help = "Подгоняет тарифы и факты о преподавателе под макет"

    def handle(self, *args, **options):
        for name, features in FEATURES.items():
            Tariff.objects.filter(course__isnull=True, name=name).update(features=features)
        Teacher.objects.filter(name="Валерия Владимировна").update(bio=VALERIA_FACTS)
        self.stdout.write(self.style.SUCCESS("Тарифы и факты обновлены."))
